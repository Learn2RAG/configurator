from functools import cache
from pathlib import Path

from babel import negotiate_locale
from babel.support import NullTranslations, Translations
from werkzeug.datastructures import LanguageAccept
from werkzeug.http import parse_accept_header

TRANSLATIONS_PATH = Path(__file__).parent / 'translations'
LANGUAGES = ['en', 'de']
DEFAULT_LANGUAGE = 'de'


def select_language(accept_language: str | None) -> str:
    languages = parse_accept_header(accept_language, LanguageAccept)
    return negotiate_locale((x.replace('-', '_') for x in languages.values()), LANGUAGES) or DEFAULT_LANGUAGE


@cache
def get_translations(language: str) -> NullTranslations:
    return Translations.load(TRANSLATIONS_PATH, [language])


def ai_notice(language: str) -> dict[str, str]:
    translations = get_translations(language)
    _ = translations.gettext
    return {
        'title': _('AI notice'),
        'interaction': _('You are interacting with an AI system, not a human.'),
        'content': _('Answers are generated by AI and may contain content that has been changed or adapted by the AI. Please verify important information.'),
    }
